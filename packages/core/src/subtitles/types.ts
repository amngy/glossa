/** A single timed subtitle line. Times are in seconds. */
export interface Cue {
  start: number;
  end: number;
  /** Plain text. May contain "\n" for multi-line cues. */
  text: string;
}

export interface SubtitleTrack {
  /** BCP 47 language tag, e.g. "es" or "pt-BR". */
  lang: string;
  label?: string;
  /** True when the track was produced by speech recognition. */
  autoGenerated?: boolean;
  cues: Cue[];
}
