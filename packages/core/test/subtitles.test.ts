import { describe, expect, it } from 'vitest';
import {
  cleanCueText,
  findActiveCueIndex,
  findBestOverlap,
  findCueIndexAtOrBefore,
  parseTextSubtitles,
  parseTimestamp,
  parseYouTubeJson3,
} from '../src';

describe('parseTimestamp', () => {
  it('handles VTT, short VTT and SRT forms', () => {
    expect(parseTimestamp('00:01:02.345')).toBeCloseTo(62.345);
    expect(parseTimestamp('01:02.5')).toBeCloseTo(62.5);
    expect(parseTimestamp('01:00:00,001')).toBeCloseTo(3600.001);
    expect(parseTimestamp('nonsense')).toBeNull();
  });
});

describe('parseTextSubtitles', () => {
  it('parses WebVTT with header, notes, settings and markup', () => {
    const vtt = `WEBVTT
Kind: captions

NOTE this is ignored

1
00:00:01.000 --> 00:00:03.500 align:start position:10%
<v Ana>¿Dónde está</v> la <i>biblioteca</i>?

00:00:04.000 --> 00:00:06.000
- Hola &amp; adiós
- ¡Ciao!
`;
    expect(parseTextSubtitles(vtt)).toEqual([
      { start: 1, end: 3.5, text: '¿Dónde está la biblioteca?' },
      { start: 4, end: 6, text: '- Hola & adiós\n- ¡Ciao!' },
    ]);
  });

  it('parses SRT with CRLF line endings and a BOM', () => {
    const srt = '﻿1\r\n00:00:01,000 --> 00:00:02,000\r\nHallo Welt\r\n\r\n2\r\n00:00:02,500 --> 00:00:04,000\r\nWie geht\'s?\r\n';
    expect(parseTextSubtitles(srt)).toEqual([
      { start: 1, end: 2, text: 'Hallo Welt' },
      { start: 2.5, end: 4, text: "Wie geht's?" },
    ]);
  });
});

describe('parseYouTubeJson3', () => {
  it('parses manual tracks', () => {
    const data = {
      events: [
        { tStartMs: 1000, dDurationMs: 2000, segs: [{ utf8: 'Bonjour\nà tous' }] },
        { tStartMs: 3500, dDurationMs: 1000, segs: [{ utf8: 'Merci' }] },
      ],
    };
    expect(parseYouTubeJson3(data)).toEqual([
      { start: 1, end: 3, text: 'Bonjour\nà tous' },
      { start: 3.5, end: 4.5, text: 'Merci' },
    ]);
  });

  it('flattens rolling auto-generated captions into non-overlapping lines', () => {
    const data = {
      events: [
        { tStartMs: 0, dDurationMs: 100000, id: 1, wWinId: 1 },
        { tStartMs: 0, dDurationMs: 4000, wWinId: 1, segs: [{ utf8: 'so' }, { utf8: ' today', tOffsetMs: 300 }] },
        { tStartMs: 2000, dDurationMs: 2000, wWinId: 1, aAppend: 1, segs: [{ utf8: '\n' }] },
        { tStartMs: 2000, dDurationMs: 3000, wWinId: 1, segs: [{ utf8: 'we are' }, { utf8: ' going', tOffsetMs: 400 }] },
      ],
    };
    expect(parseYouTubeJson3(data, { autoGenerated: true })).toEqual([
      { start: 0, end: 2, text: 'so today' },
      { start: 2, end: 5, text: 'we are going' },
    ]);
  });

  it('keeps a line on screen while another row shows with it', () => {
    // A two-row subtitle sent as two events: the second row appears and goes away before the first.
    const data = {
      events: [
        { tStartMs: 0, dDurationMs: 6000, wWinId: 1, segs: [{ utf8: 'ずっと前から' }] },
        { tStartMs: 2000, dDurationMs: 2000, wWinId: 2, segs: [{ utf8: '好きでした' }] },
        { tStartMs: 6000, dDurationMs: 1000, segs: [{ utf8: '次' }] },
      ],
    };
    expect(parseYouTubeJson3(data)).toEqual([
      { start: 0, end: 2, text: 'ずっと前から' },
      { start: 2, end: 4, text: 'ずっと前から\n好きでした' },
      { start: 4, end: 6, text: 'ずっと前から' },
      { start: 6, end: 7, text: '次' },
    ]);
  });

  it('treats a small overlap between lines as timing slop', () => {
    const data = {
      events: [
        { tStartMs: 0, dDurationMs: 2200, segs: [{ utf8: 'one' }] },
        { tStartMs: 2000, dDurationMs: 2000, segs: [{ utf8: 'two' }] },
      ],
    };
    expect(parseYouTubeJson3(data)).toEqual([
      { start: 0, end: 2, text: 'one' },
      { start: 2, end: 4, text: 'two' },
    ]);
  });

  it('drops sound descriptions such as [Music]', () => {
    const data = {
      events: [
        { tStartMs: 0, dDurationMs: 2000, segs: [{ utf8: '[Music]' }] },
        { tStartMs: 2000, dDurationMs: 2000, segs: [{ utf8: '[Aplausos] hola a todos' }] },
        { tStartMs: 4000, dDurationMs: 2000, segs: [{ utf8: '♪ ♪' }] },
      ],
    };
    expect(parseYouTubeJson3(data, { autoGenerated: true })).toEqual([
      { start: 2, end: 4, text: 'hola a todos' },
    ]);
  });

  it('returns no cues for unexpected input', () => {
    expect(parseYouTubeJson3(null)).toEqual([]);
    expect(parseYouTubeJson3({ events: 'x' })).toEqual([]);
  });
});

describe('cleanCueText', () => {
  it('removes bracketed sound cues, whole-line parenthetical cues and music notes', () => {
    expect(cleanCueText('[Music]')).toBe('');
    expect(cleanCueText('(door slams)')).toBe('');
    expect(cleanCueText('[Music] (applause)')).toBe('');
    expect(cleanCueText('♪ la la la ♪')).toBe('la la la');
    expect(cleanCueText('Hola [risas]\n[Música]\nadiós')).toBe('Hola\nadiós');
  });

  it('keeps parentheses that are part of speech', () => {
    expect(cleanCueText('Mi hermano (el mayor) vive aquí')).toBe('Mi hermano (el mayor) vive aquí');
  });
});

describe('cue lookup', () => {
  const cues = [
    { start: 1, end: 2, text: 'a' },
    { start: 3, end: 4, text: 'b' },
    { start: 4, end: 6, text: 'c' },
  ];

  it('finds the active cue or reports a gap', () => {
    expect(findActiveCueIndex(cues, 0.5)).toBe(-1);
    expect(findActiveCueIndex(cues, 1.5)).toBe(0);
    expect(findActiveCueIndex(cues, 2.5)).toBe(-1);
    expect(findActiveCueIndex(cues, 4)).toBe(2);
    expect(findActiveCueIndex(cues, 7)).toBe(-1);
    expect(findCueIndexAtOrBefore(cues, 2.5)).toBe(0);
  });

  it('pairs a line with the most-overlapping translation', () => {
    const translation = [
      { start: 0.9, end: 2.1, text: 'A' },
      { start: 2.9, end: 4.6, text: 'B' },
      { start: 4.6, end: 6, text: 'C' },
    ];
    expect(findBestOverlap(translation, 1, 2)?.text).toBe('A');
    expect(findBestOverlap(translation, 3, 4)?.text).toBe('B');
    expect(findBestOverlap(translation, 4, 6)?.text).toBe('C');
    expect(findBestOverlap(translation, 10, 11)).toBeUndefined();
  });
});
