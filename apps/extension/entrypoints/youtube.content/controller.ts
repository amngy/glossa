import { browser } from '#imports';
import {
  baseLanguage,
  isWebmInit,
  parseTextSubtitles,
  parseYouTubeJson3,
  WebmDemuxer,
  type Cue,
  type SubtitleTrack,
} from '@glossa/core';
import { errorMessage, SubtitleController, TRANSCRIPT_KEY } from '@/components/overlay/controller';
import type { TrackOption } from '@/components/overlay/state';
import { toBase64, type AheadAudio } from '@/lib/asr';
import {
  FROM_PAGE,
  TO_PAGE,
  trackKey,
  type CaptionTrackInfo,
  type ExtensionMessageBody,
  type PageMessage,
} from '@/lib/youtube-bridge';

/** Space between YouTube's control bar and the subtitles. */
const CONTROLS_MARGIN = 8;
const TRACK_LOAD_TIMEOUT_MS = 6000;
/** `TrackOption.key` of a subtitle file the viewer loaded. */
const FILE_KEY = 'file';
/** Look-ahead audio kept until transcription starts: appends of about 0.2 s each, so about a minute. */
const AHEAD_BACKLOG = 300;

type AudioAppend = Extract<PageMessage, { type: 'audio-append' }>;

function parseCaptionBody(body: string, autoGenerated: boolean): Cue[] | null {
  const text = body.trimStart();
  if (text.startsWith('{')) {
    try {
      return parseYouTubeJson3(JSON.parse(text), { autoGenerated });
    } catch {
      return null;
    }
  }
  if (text.startsWith('WEBVTT')) return parseTextSubtitles(text);
  return null;
}

/**
 * Picks the track in the spoken language: YouTube's speech-recognition track
 * reveals which language is spoken, and a human-made track in that language
 * is preferred over the automatic one.
 */
export function chooseDefaultTrack(tracks: CaptionTrackInfo[]): CaptionTrackInfo | undefined {
  const automatic = tracks.find((t) => t.kind === 'asr');
  const spoken = automatic && baseLanguage(automatic.languageCode);
  const manual = spoken
    ? tracks.find((t) => t.kind !== 'asr' && baseLanguage(t.languageCode) === spoken)
    : undefined;
  return manual ?? automatic ?? tracks[0];
}

/** Connects YouTube's player to the overlay: loads its captions through the page hook and sizes the overlay. */
export class YouTubeController extends SubtitleController {
  private videoId: string | null = null;
  private trackUrl: URL | null = null;
  private loadedTrackKey: string | null = null;
  private captionTracks: CaptionTrackInfo[] = [];
  /** A subtitle file the viewer loaded, for videos without captions. */
  private fileTrack: SubtitleTrack | null = null;
  private sawCaptionsForVideo = false;
  private trackRequestAttempts = 0;
  private observedPlayer: Element | null = null;
  private observedBar: Element | null = null;
  private resizeObserver?: ResizeObserver;
  /** Look-ahead transcription (#44): a demuxer per audio SourceBuffer in the page, and audio read so far. */
  private readonly demuxers = new Map<number, WebmDemuxer>();
  private aheadBacklog: { videoId?: string; audio: AheadAudio }[] = [];
  private sendingAhead = false;

  protected onStart(): void {
    this.store.set({ canLoadFile: true });
    this.ctx.addEventListener(window, 'message', (event) => this.onPageMessage(event));
    this.ctx.addEventListener(window, 'wxt:locationchange', () => this.onNavigate());
    const onYouTubeNavigate = () => this.onNavigate();
    document.addEventListener('yt-navigate-finish', onYouTubeNavigate);
    this.ctx.onInvalidated(() => {
      document.removeEventListener('yt-navigate-finish', onYouTubeNavigate);
      this.resizeObserver?.disconnect();
      document.documentElement.removeAttribute('data-glossa-active');
    });

    this.injectPageStyles();
    this.onNavigate();
    this.postToPage({ type: 'replay' });
  }

  // ---------------------------------------------------------------- loading

  private postToPage(message: ExtensionMessageBody): void {
    window.postMessage({ source: TO_PAGE, ...message }, location.origin);
  }

  private onNavigate(): void {
    const id = location.pathname === '/watch' ? new URLSearchParams(location.search).get('v') : null;
    if (id === this.videoId) return;

    this.videoId = id;
    this.trackUrl = null;
    this.loadedTrackKey = null;
    this.captionTracks = [];
    this.fileTrack = null;
    this.clearTranscript();
    this.sawCaptionsForVideo = false;
    this.trackRequestAttempts = 0;
    this.sendingAhead = false;
    // While look-ahead is on, the player's audio is read from the start of each video, so it's there when transcription starts.
    this.postToPage({ type: 'audio-tap', on: !!id && this.store.get().settings.lookAhead });
    this.setTrack(undefined, {
      active: id !== null,
      status: id ? 'loading' : 'idle',
      tracks: [],
      trackKey: null,
      languageGuessed: false,
    });
    this.updatePageFlag();
    // Give the player a moment: if the viewer already has captions on, YouTube loads them itself.
    if (id) this.ctx.setTimeout(() => this.requestTracks(), 1000);
  }

  private requestTracks(): void {
    if (!this.videoId) return;
    this.trackRequestAttempts++;
    this.postToPage({ type: 'get-tracks' });
  }

  private onPageMessage(event: MessageEvent): void {
    if (event.source !== window || event.origin !== location.origin) return;
    const data = event.data as PageMessage | undefined;
    if (data?.source !== FROM_PAGE) return;
    if (data.type === 'tracks') this.onTracks(data.videoId, data.tracks);
    else if (data.type === 'timedtext') void this.onCaptions(data.url, data.body);
    else if (data.type === 'audio-append') this.onAudioAppend(data);
  }

  /** Reads Opus frames from an audio append; they go to the offscreen document once transcription runs. */
  private onAudioAppend(append: AudioAppend): void {
    // shortcut: WebM/Opus only; MP4/AAC audio (branded Chrome, Edge) needs its own demuxer.
    if (!append.mime.startsWith('audio/webm')) return;
    const bytes = new Uint8Array(append.data);
    let demuxer = this.demuxers.get(append.buffer);
    if (!demuxer || isWebmInit(bytes)) {
      demuxer = new WebmDemuxer();
      // Without its init segment, the stream was joined in the middle.
      if (!isWebmInit(bytes)) demuxer.resync();
      this.demuxers.set(append.buffer, demuxer);
    }
    const frames = demuxer.push(bytes);
    if (append.replayed) demuxer.resync();
    const track = demuxer.track;
    // Ads and AI dubs are read (to keep the stream in step) but not transcribed.
    if (append.ad || append.dubbed || frames.length === 0 || track?.codec !== 'A_OPUS') return;
    const audio: AheadAudio = {
      glossaAhead: true,
      buffer: append.buffer,
      sampleRate: track.sampleRate ?? 48000,
      channels: track.channels ?? 2,
      description: track.codecPrivate && toBase64(track.codecPrivate),
      frames: frames.map((frame) => ({ time: frame.time + append.timestampOffset, data: toBase64(frame.data) })),
    };
    this.aheadBacklog.push({ videoId: append.videoId, audio });
    if (this.aheadBacklog.length > AHEAD_BACKLOG) this.aheadBacklog.shift();
    if (this.sendingAhead && this.transcribing && append.videoId === this.videoId) this.sendAhead(audio);
  }

  /** Straight to the offscreen document, which only takes it while it transcribes this tab. */
  private sendAhead(audio: AheadAudio): void {
    void browser.runtime.sendMessage(audio).catch(() => {});
  }

  private onTracks(videoId: string | null, tracks: CaptionTrackInfo[]): void {
    if (!this.videoId) return;
    if (videoId !== this.videoId) {
      // The player hasn't switched to the new video yet.
      if (this.trackRequestAttempts < 10) this.ctx.setTimeout(() => this.requestTracks(), 700);
      return;
    }
    this.captionTracks = tracks;
    this.store.set({ tracks: this.trackOptions() });
    if (tracks.length === 0) {
      if (!this.fileTrack && !this.transcript) this.store.set({ status: 'no-subtitles' });
      return;
    }
    if (!this.fileTrack && !this.sawCaptionsForVideo && this.store.get().settings.enabled) {
      const preferred = chooseDefaultTrack(tracks);
      if (preferred) this.loadTrack(preferred);
    }
  }

  private trackOptions(): TrackOption[] {
    const options = this.captionTracks.map((t) => ({ key: trackKey(t), name: t.name }));
    if (this.fileTrack) options.push({ key: FILE_KEY, name: this.fileTrack.label ?? 'Subtitle file' });
    const transcript = this.transcriptOption();
    if (transcript) options.push(transcript);
    return options;
  }

  override loadFile(file: File): void {
    void this.readSubtitleFile(file).then((track) => {
      if (!track) return;
      this.fileTrack = track;
      this.useFile();
    });
  }

  private useFile(): void {
    if (!this.fileTrack) return;
    this.loadedTrackKey = FILE_KEY;
    this.trackUrl = null; // YouTube's translation belongs to its own track, not the file
    // The file's language is a guess from its name or text, so the viewer can always correct it.
    this.setTrack(this.fileTrack, { trackKey: FILE_KEY, languageGuessed: true, tracks: this.trackOptions() });
    this.updatePageFlag();
  }

  override setTrackLanguage(lang: string): void {
    const { track } = this.store.get();
    if (!track || !this.fileTrack) return;
    this.fileTrack = { ...track, lang };
    this.useFile();
  }

  protected override onTranscriptionStart(): void {
    this.store.set({ tracks: this.trackOptions() });
    if (!this.store.get().settings.lookAhead) return;
    // In case look-ahead was turned on during this video; then only audio appended from now on is read.
    this.postToPage({ type: 'audio-tap', on: true });
    this.sendingAhead = true;
    for (const { videoId, audio } of this.aheadBacklog) if (videoId === this.videoId) this.sendAhead(audio);
  }

  selectTrack(key: string): void {
    if (key === TRANSCRIPT_KEY) {
      this.showTranscript();
      return;
    }
    if (key === FILE_KEY) {
      this.useFile();
      return;
    }
    const track = this.captionTracks.find((t) => trackKey(t) === key);
    if (track) this.loadTrack(track);
  }

  /** Asks YouTube's player to load a track; the hook then forwards the downloaded file to `onCaptions`. */
  private loadTrack(track: CaptionTrackInfo): void {
    const key = trackKey(track);
    if (key === this.loadedTrackKey) return;
    const videoId = this.videoId;
    this.store.set({ status: 'loading', error: undefined });
    this.postToPage({ type: 'load-track', track });
    // The captions module sometimes isn't ready on the first try.
    this.ctx.setTimeout(() => {
      if (this.videoId === videoId && this.loadedTrackKey !== key) this.postToPage({ type: 'load-track', track });
    }, 2000);
    this.ctx.setTimeout(() => {
      if (this.videoId === videoId && this.loadedTrackKey !== key && this.store.get().status === 'loading') {
        this.store.set({
          status: 'error',
          error: 'YouTube didn’t load these subtitles. Try turning captions (CC) on in the player.',
        });
      }
    }, TRACK_LOAD_TIMEOUT_MS);
  }

  private async onCaptions(rawUrl: string, body: string): Promise<void> {
    let url: URL;
    try {
      url = new URL(rawUrl);
    } catch {
      return;
    }
    if (!this.videoId || url.searchParams.get('v') !== this.videoId) return;
    const lang = url.searchParams.get('lang');
    if (!lang) return;
    this.sawCaptionsForVideo = true;

    const kind = url.searchParams.get('kind') ?? '';
    const key = trackKey({ languageCode: lang, kind });
    const tlang = url.searchParams.get('tlang');

    if (tlang) {
      // The viewer chose YouTube's auto-translate: keep the original language as the main line.
      const original = new URL(url);
      original.searchParams.delete('tlang');
      if (key !== this.loadedTrackKey) await this.loadPrimaryTrack(original, lang, kind);
      const { settings, track } = this.store.get();
      if (track && baseLanguage(tlang) === baseLanguage(settings.nativeLanguage)) {
        const cues = parseCaptionBody(body, kind === 'asr');
        if (cues?.length) this.store.set({ translationTrack: { lang: tlang, cues } });
      }
      return;
    }

    if (key !== this.loadedTrackKey) await this.loadPrimaryTrack(url, lang, kind, body);
  }

  private async fetchCues(url: URL, autoGenerated: boolean): Promise<Cue[]> {
    const request = new URL(url);
    request.searchParams.set('fmt', 'json3');
    const response = await fetch(request, { credentials: 'include' });
    if (!response.ok) throw new Error(`YouTube responded with ${response.status}`);
    const text = await response.text();
    return text.trim() ? (parseCaptionBody(text, autoGenerated) ?? []) : [];
  }

  private async loadPrimaryTrack(url: URL, lang: string, kind: string, body?: string): Promise<void> {
    const key = trackKey({ languageCode: lang, kind });
    const videoId = this.videoId;
    this.loadedTrackKey = key;

    let cues = body ? parseCaptionBody(body, kind === 'asr') : null;
    if (!cues) {
      try {
        cues = await this.fetchCues(url, kind === 'asr');
      } catch (error) {
        if (this.loadedTrackKey === key) {
          this.loadedTrackKey = null;
          this.store.set({ status: 'error', error: `Couldn’t load subtitles: ${errorMessage(error)}` });
        }
        return;
      }
    }
    if (videoId !== this.videoId || this.loadedTrackKey !== key) return;

    const info = this.captionTracks.find((t) => trackKey(t) === key);
    this.trackUrl = url;
    this.setTrack({ lang, label: info?.name, autoGenerated: kind === 'asr', cues }, { trackKey: key, languageGuessed: false });
    this.updatePageFlag();
    await this.loadTranslationTrack();
  }

  /** Fetches YouTube's own machine translation of the current track, which is free and pre-timed. */
  private async loadTranslationTrack(): Promise<void> {
    const { track, settings } = this.store.get();
    const url = this.trackUrl;
    if (!track || !url) return;
    this.store.set({ translationTrack: undefined, lineTranslations: new Map() });
    if (baseLanguage(track.lang) === baseLanguage(settings.nativeLanguage)) return;

    const translationUrl = new URL(url);
    translationUrl.searchParams.set('tlang', settings.nativeLanguage);
    this.translationTrackPending = true;
    try {
      const cues = await this.fetchCues(translationUrl, track.autoGenerated ?? false);
      if (this.store.get().track === track && cues.length > 0) {
        this.store.set({ translationTrack: { lang: settings.nativeLanguage, cues } });
      }
    } catch {
      // Not every video can be auto-translated; lines are then translated one by one.
    } finally {
      this.translationTrackPending = false;
    }
    this.translateAround(this.store.get().displayIndex);
  }

  protected override onNativeLanguageChanged(): void {
    void this.loadTranslationTrack();
  }

  protected override onEnabledChanged(enabled: boolean): void {
    this.updatePageFlag();
    if (enabled && !this.loadedTrackKey) this.requestTracks();
  }

  // ------------------------------------------------------------------ layout

  /** Watches the player's size and that of its control bar (YouTube may create the bar later). */
  private observePlayer(player: Element, bar: Element | null): void {
    this.observedPlayer = player;
    this.observedBar = bar;
    this.resizeObserver?.disconnect();
    this.resizeObserver = new ResizeObserver(() => {
      const box = player.getBoundingClientRect();
      // Measured from the bar's top edge, since the bar may not reach the bottom of the player.
      const barBox = bar?.getBoundingClientRect();
      const controlsHeight = barBox && barBox.height > 0 ? Math.max(0, Math.round(box.bottom - barBox.top + CONTROLS_MARGIN)) : 0;
      this.store.set({ playerHeight: Math.round(box.height), controlsHeight });
    });
    this.resizeObserver.observe(player);
    if (bar) this.resizeObserver.observe(bar);
  }

  protected updateFrame(): HTMLVideoElement | null {
    const player = document.getElementById('movie_player');
    const bar = player?.querySelector('.ytp-chrome-bottom') ?? null;
    if (player && (player !== this.observedPlayer || bar !== this.observedBar)) this.observePlayer(player, bar);
    this.store.set({
      controlsVisible: !!player && !player.classList.contains('ytp-autohide'),
      adShowing: !!player?.classList.contains('ad-showing'),
    });
    return player?.querySelector('video') ?? null;
  }

  protected source(time: number): { url: string; title: string } {
    return {
      url: `https://www.youtube.com/watch?v=${this.videoId}&t=${Math.floor(time)}s`,
      title: document.title.replace(/^\(\d+\)\s*/, '').replace(/\s*-\s*YouTube$/, ''),
    };
  }

  // ------------------------------------------------------------ page glue

  /** Hides YouTube's own captions while Glossa shows its overlay. */
  private injectPageStyles(): void {
    const style = document.createElement('style');
    style.dataset.glossa = '';
    style.textContent =
      'html[data-glossa-active] #movie_player .ytp-caption-window-container { display: none !important; }';
    (document.head ?? document.documentElement).append(style);
    this.ctx.onInvalidated(() => style.remove());
  }

  private updatePageFlag(): void {
    const { settings, track, active } = this.store.get();
    document.documentElement.toggleAttribute('data-glossa-active', settings.enabled && active && !!track);
  }
}
